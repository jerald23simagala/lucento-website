// Generates src/styles/tokens.css from design/tokens.json (the Lucento design system export).
// Usage: node scripts/build-tokens.mjs [--check]
//   --check  exits non-zero if tokens.css is out of date instead of rewriting it.
import { readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../design/tokens.json', import.meta.url);
const out = new URL('../src/styles/tokens.css', import.meta.url);
const data = JSON.parse(readFileSync(src, 'utf8'));

const colors = data.color.tokens;
const byName = new Map(colors.map((t) => [t.name, t]));

function resolve(value, theme, seen = new Set()) {
  const match = /^\{([a-z0-9-]+)\}$/.exec(value);
  if (!match) return value;
  const name = match[1];
  if (seen.has(name)) throw new Error(`Circular token reference: ${name}`);
  const target = byName.get(name);
  if (!target) throw new Error(`Unknown token reference: ${name}`);
  seen.add(name);
  return resolve(target.value[theme], theme, seen);
}

const themed = (tokens, theme) =>
  tokens.map((t) => `  --${t.name}: ${resolve(t.value[theme], theme)};`).join('\n');
const flat = (group) => group.tokens.map((t) => `  --${t.name}: ${t.value};`).join('\n');

const css = `/* Generated by scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */
:root {
  color-scheme: light;
${themed(colors, 'light')}
${themed(data.shadow.tokens, 'light')}
${flat(data.spacing)}
${flat(data.radius)}
${flat(data.size)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${themed(colors, 'dark').replace(/^/gm, '  ')}
${themed(data.shadow.tokens, 'dark').replace(/^/gm, '  ')}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${themed(colors, 'dark')}
${themed(data.shadow.tokens, 'dark')}
}
`;

// ---------------------------------------------------------------------------------------------------------------
// Horizon: the website's own visual system (design/horizon.tokens.json, copied from lucento-studio
// system/horizon.tokens.json, where DESIGN.md and the contrast report are generated). It writes
// src/styles/horizon-tokens.css. The app palette above stays for the pages that still use it.
const horizonSrc = new URL('../design/horizon.tokens.json', import.meta.url);
const horizonOut = new URL('../src/styles/horizon-tokens.css', import.meta.url);
const hz = JSON.parse(readFileSync(horizonSrc, 'utf8'));
const ramp = hz.color.ramps['crest-blue'].steps;
const hzByName = new Map(hz.color.tokens.map((t) => [t.name, t]));
function hzResolve(value, theme, seen = new Set()) {
  const match = /^\{([a-z0-9-]+)\}$/.exec(value);
  if (!match) return value;
  const ref = match[1];
  const step = /^crest-blue-(\d+)$/.exec(ref);
  if (step) {
    if (!ramp[step[1]]) throw new Error(`Unknown ramp step: ${ref}`);
    return ramp[step[1]];
  }
  if (seen.has(ref)) throw new Error(`Circular token reference: ${ref}`);
  seen.add(ref);
  const target = hzByName.get(ref);
  if (!target) throw new Error(`Unknown token reference: ${ref}`);
  return hzResolve(target.value[theme], theme, seen);
}
const hzThemed = (theme, indent) =>
  [
    ...hz.color.tokens.map((t) => `--${t.name}: ${hzResolve(t.value[theme], theme)};`),
    ...hz.shadow.tokens.map((t) => `--${t.name}: ${t.value[theme]};`),
  ]
    .map((line) => indent + line)
    .join('\n');
const hzFlat = (list) => list.map((t) => `  --${t.name}: ${t.value};`).join('\n');
const hzType = hz.type.scale
  .map((s) =>
    [
      `  --text-${s.name}: ${s.fontSize};`,
      `  --leading-${s.name}: ${s.lineHeight};`,
      `  --weight-${s.name}: ${s.fontWeight};`,
      `  --tracking-${s.name}: ${s.letterSpacing};`,
    ].join('\n'),
  )
  .join('\n');
const nightScene = '--scene: url("/brand/scenery/scenery_midnight_panorama.webp");';
const horizonCss = `/* Generated by scripts/build-tokens.mjs from design/horizon.tokens.json. Do not edit by hand. */
:root {
  color-scheme: light;
${hzThemed('light', '  ')}
${Object.entries(ramp)
  .map(([k, v]) => `  --crest-blue-${k}: ${v};`)
  .join('\n')}
  --font-sans: ${hz.type.families.sans};
${hzType}
${hzFlat(hz.spacing.tokens)}
${hzFlat(hz.radius.tokens)}
${hzFlat(hz.size.tokens)}
${hzFlat(hz.motion.tokens)}
  --scene: url("/brand/scenery/scenery_sunrise_panorama.webp");
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${hzThemed('dark', '    ')}
    ${nightScene}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${hzThemed('dark', '  ')}
  ${nightScene}
}

/* Night in either theme: the footer, where the page's day ends. */
.theme-night {
  color-scheme: dark;
${hzThemed('dark', '  ')}
  ${nightScene}
}

/* Reduced motion: everything decorative holds still. */
@media (prefers-reduced-motion: reduce) {
  :root {
    --dur-quick: 0ms;
    --dur-base: 0ms;
    --dur-enter: 0ms;
    --dur-hero: 0ms;
    --stagger: 0ms;
  }
}
`;

const outputs = [
  [out, css, 'src/styles/tokens.css', `${colors.length} colour tokens`],
  [horizonOut, horizonCss, 'src/styles/horizon-tokens.css', `${hz.color.tokens.length} Horizon colour tokens`],
];
if (process.argv.includes('--check')) {
  let stale = false;
  for (const [file, content, label] of outputs) {
    let current = '';
    try {
      current = readFileSync(file, 'utf8');
    } catch {
      // Missing file counts as out of date.
    }
    if (current !== content) {
      console.error(`${label} is out of date. Run: npm run tokens`);
      stale = true;
    } else {
      console.log(`${label} is up to date.`);
    }
  }
  if (stale) process.exit(1);
} else {
  for (const [file, content, label, what] of outputs) {
    writeFileSync(file, content);
    console.log(`Wrote ${what} to ${label}`);
  }
}
